-- ============================================================
-- 工资管理系统 Oracle DDL
-- 目标库：TRMUSR (Oracle 23ai Free)
-- 约定：所有表使用 SLR_ 前缀，避免与现有业务表冲突
-- 执行方式：java -cp <ojdbc.jar> InitSchema.java
-- ============================================================

-- 导入批次表
CREATE TABLE SLR_IMPORT_BATCH (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FILE_NAME     VARCHAR2(255)  NOT NULL,
    IMPORT_TIME   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    IMPORT_BY     VARCHAR2(50),
    TOTAL_ROWS    NUMBER(6)      DEFAULT 0,
    OK_ROWS       NUMBER(6)      DEFAULT 0,
    WARN_MSG      VARCHAR2(2000)
);

-- 工资月度记录表
CREATE TABLE SLR_SALARY_RECORD (
    ID                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    MONTH                DATE          NOT NULL,
    GRADE                VARCHAR2(10),
    POST_SALARY          NUMBER(12,2),
    REGION_ALLOWANCE     NUMBER(12,2),
    BONUS                NUMBER(12,2),
    OTHER_INCOME         NUMBER(12,2),
    POST_SUBSIDY         NUMBER(12,2),
    OVERTIME_PAY         NUMBER(12,2),
    HOUSING_SUBSIDY      NUMBER(12,2),
    WORK_ALLOWANCE       NUMBER(12,2),
    OTHER_ADJUST         NUMBER(12,2),
    TOTAL_INCOME         NUMBER(12,2),
    PENSION_PERSONAL     NUMBER(12,2),
    UNEMPLOYMENT_PERSONAL NUMBER(12,2),
    MEDICAL_PERSONAL     NUMBER(12,2),
    HOUSING_FUND_PERSONAL NUMBER(12,2),
    ANNUITY_PERSONAL     NUMBER(12,2),
    INCOME_TAX           NUMBER(12,2),
    TOTAL_DEDUCTION      NUMBER(12,2),
    NET_PAY              NUMBER(12,2),
    TOTAL_SALARY         NUMBER(12,2),
    PENSION_COMPANY      NUMBER(12,2),
    UNEMPLOYMENT_COMPANY NUMBER(12,2),
    MEDICAL_COMPANY      NUMBER(12,2),
    INJURY_COMPANY       NUMBER(12,2),
    MATERNITY_COMPANY    NUMBER(12,2),
    HOUSING_FUND_COMPANY NUMBER(12,2),
    ANNUITY_COMPANY      NUMBER(12,2),
    COMPANY_TOTAL        NUMBER(12,2),
    OTHER_BONUS          NUMBER(12,2),
    ANNUAL_BONUS         NUMBER(12,2),
    ANNUAL_BONUS_TAX     NUMBER(12,2),
    ANNUAL_BONUS_NET     NUMBER(12,2),
    FORMULA_JSON         CLOB,
    SOURCE_BATCH_ID      NUMBER REFERENCES SLR_IMPORT_BATCH(ID),
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_SLR_RECORD_MONTH UNIQUE (MONTH)
);

-- 批注表
CREATE TABLE SLR_SALARY_COMMENT (
    ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    RECORD_ID  NUMBER        NOT NULL REFERENCES SLR_SALARY_RECORD(ID) ON DELETE CASCADE,
    FIELD_CODE VARCHAR2(20)  NOT NULL,
    AUTHOR     VARCHAR2(50),
    CONTENT    VARCHAR2(4000) NOT NULL,
    ITEMS_JSON CLOB,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 操作日志表
CREATE TABLE SLR_OPERATION_LOG (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OPERATOR    VARCHAR2(50),
    ACTION      VARCHAR2(50),
    TARGET_TYPE VARCHAR2(30),
    TARGET_ID   NUMBER,
    DETAIL      CLOB,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 系统用户表
CREATE TABLE SLR_APP_USER (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USERNAME      VARCHAR2(50)  NOT NULL,
    PASSWORD_HASH VARCHAR2(200) NOT NULL,
    DISPLAY_NAME  VARCHAR2(50),
    ROLE          VARCHAR2(20)  DEFAULT 'VIEWER',
    ENABLED       NUMBER(1)     DEFAULT 1,
    CREATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_SLR_USER_NAME UNIQUE (USERNAME)
);

-- 索引
CREATE INDEX IDX_SLR_COMMENT_RECORD ON SLR_SALARY_COMMENT(RECORD_ID);
CREATE INDEX IDX_SLR_RECORD_GRADE  ON SLR_SALARY_RECORD(GRADE);
CREATE INDEX IDX_SLR_LOG_TIME      ON SLR_OPERATION_LOG(CREATED_AT);

-- 表注释
COMMENT ON TABLE SLR_IMPORT_BATCH   IS 'Excel 导入批次';
COMMENT ON TABLE SLR_SALARY_RECORD  IS '工资月度记录';
COMMENT ON TABLE SLR_SALARY_COMMENT IS '工资批注（挂接月份+字段）';
COMMENT ON TABLE SLR_OPERATION_LOG  IS '操作审计日志';
COMMENT ON TABLE SLR_APP_USER       IS '系统用户';

-- 关键字段注释
COMMENT ON COLUMN SLR_SALARY_RECORD.MONTH          IS '工资月份(当月1日)';
COMMENT ON COLUMN SLR_SALARY_RECORD.GRADE         IS '考核等级(A1/A2/A3/B1/B2/C)';
COMMENT ON COLUMN SLR_SALARY_RECORD.TOTAL_INCOME  IS '加项合计=SUM(C:K)';
COMMENT ON COLUMN SLR_SALARY_RECORD.TOTAL_DEDUCTION IS '扣项合计=SUM(M:R)';
COMMENT ON COLUMN SLR_SALARY_RECORD.NET_PAY       IS '实发金额=L-S';
COMMENT ON COLUMN SLR_SALARY_RECORD.TOTAL_SALARY IS '总薪资=实发金额+其他奖金+年度奖金实发';
COMMENT ON COLUMN SLR_SALARY_RECORD.COMPANY_TOTAL IS '公司合计=SUM(U:AA)';
COMMENT ON COLUMN SLR_SALARY_RECORD.FORMULA_JSON  IS 'Excel 原始公式(JSON)';
COMMENT ON COLUMN SLR_SALARY_COMMENT.FIELD_CODE   IS '字段标识(F/K/AC/AD等)';
COMMENT ON COLUMN SLR_SALARY_COMMENT.ITEMS_JSON   IS '结构化明细(二期)';

COMMIT;
