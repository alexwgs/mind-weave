-- 保险箱：分组表
CREATE TABLE TK_VAULT_GROUP (
    ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OWNER      VARCHAR2(50) NOT NULL,
    NAME       VARCHAR2(100) NOT NULL,
    SORT_ORDER NUMBER(6) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 保险箱：凭证条目表（密码 AES-256-GCM 加密存储）
CREATE TABLE TK_VAULT_ITEM (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OWNER       VARCHAR2(50) NOT NULL,
    GROUP_ID    NUMBER REFERENCES TK_VAULT_GROUP(ID) ON DELETE SET NULL,
    NAME        VARCHAR2(200) NOT NULL,
    ACCOUNT     VARCHAR2(1000),
    PASSWORD    VARCHAR2(2000),
    NOTE        VARCHAR2(4000),
    LAST_VIEW_AT TIMESTAMP,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 保险箱：自定义字段表
CREATE TABLE TK_VAULT_FIELD (
    ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ITEM_ID  NUMBER NOT NULL REFERENCES TK_VAULT_ITEM(ID) ON DELETE CASCADE,
    FIELD_KEY VARCHAR2(200) NOT NULL,
    FIELD_VALUE VARCHAR2(4000)
);

-- 附件表（保险箱图片/文件 + 文章图片/视频/文件）
CREATE TABLE TK_ATTACHMENT (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OWNER         VARCHAR2(50) NOT NULL,
    BIZ_TYPE      VARCHAR2(20) NOT NULL,          -- VAULT / ARTICLE
    BIZ_ID        NUMBER,
    ORIGINAL_NAME VARCHAR2(500),
    STORED_NAME   VARCHAR2(200) NOT NULL,
    STORAGE_PATH  VARCHAR2(1000) NOT NULL,
    MIME          VARCHAR2(100),
    SIZE_BYTES    NUMBER(18) DEFAULT 0,
    WIDTH         NUMBER(6),
    HEIGHT        NUMBER(6),
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 文章：多级分类表
CREATE TABLE TK_ARTICLE_CATEGORY (
    ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OWNER      VARCHAR2(50) NOT NULL,
    PARENT_ID  NUMBER REFERENCES TK_ARTICLE_CATEGORY(ID) ON DELETE CASCADE,
    NAME       VARCHAR2(100) NOT NULL,
    PATH       VARCHAR2(1000),
    SORT_ORDER NUMBER(6) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 文章表
CREATE TABLE TK_ARTICLE (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OWNER         VARCHAR2(50) NOT NULL,
    TITLE         VARCHAR2(300) NOT NULL,
    SUMMARY       VARCHAR2(1000),
    CATEGORY_ID   NUMBER REFERENCES TK_ARTICLE_CATEGORY(ID) ON DELETE SET NULL,
    TAGS          VARCHAR2(500),
    STATUS        VARCHAR2(20) DEFAULT 'DRAFT',    -- DRAFT / PUBLISHED
    CONTENT_MD    CLOB,
    CONTENT_HTML  CLOB,
    VIEW_COUNT    NUMBER(10) DEFAULT 0,
    COVER_ATTACH_ID NUMBER REFERENCES TK_ATTACHMENT(ID) ON DELETE SET NULL,
    IS_TOP        NUMBER(1) DEFAULT 0,
    IS_FEATURED   NUMBER(1) DEFAULT 0,
    IS_CAROUSEL   NUMBER(1) DEFAULT 0,
    COMMENT_ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    SHARE_TOKEN   VARCHAR2(64),
    SHARE_EXPIRE  TIMESTAMP,
    SHARE_PASSWORD VARCHAR2(200),
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 待办表
CREATE TABLE TK_TODO (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OWNER         VARCHAR2(50) NOT NULL,
    TITLE         VARCHAR2(300) NOT NULL,
    PROJECT       VARCHAR2(100),
    PRIORITY      VARCHAR2(10) DEFAULT 'MEDIUM',  -- HIGH / MEDIUM / LOW
    DUE_TIME      TIMESTAMP,
    REMIND_TIME   TIMESTAMP,
    REMIND_NOTE   VARCHAR2(500),
    LAST_REMIND_TIME TIMESTAMP,
    DONE          NUMBER(1) DEFAULT 0,
    REMIND_SENT   NUMBER(1) DEFAULT 0,
    OVERDUE_SENT  NUMBER(1) DEFAULT 0,
    RECUR_RULE    VARCHAR2(200),                  -- 如 WEEKLY:MON:10:00 / DAILY:09:00
    RECUR_PARENT_ID NUMBER REFERENCES TK_TODO(ID) ON DELETE SET NULL,
    RECUR_LAST_FIRED TIMESTAMP,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 待办子任务表
CREATE TABLE TK_TODO_SUB (
    ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TODO_ID    NUMBER NOT NULL REFERENCES TK_TODO(ID) ON DELETE CASCADE,
    TITLE      VARCHAR2(300) NOT NULL,
    DONE       NUMBER(1) DEFAULT 0,
    SORT_ORDER NUMBER(6) DEFAULT 0
);

-- 系统设置表（Bark URL、每日汇总时间、PIN 哈希等，按 owner+key 唯一）
CREATE TABLE TK_SETTING (
    ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OWNER      VARCHAR2(50) NOT NULL,
    SET_KEY    VARCHAR2(100) NOT NULL,
    SET_VALUE  VARCHAR2(4000),
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_TK_SETTING UNIQUE (OWNER, SET_KEY)
);

-- 常用索引
CREATE INDEX IDX_TK_ITEM_OWNER ON TK_VAULT_ITEM(OWNER);
CREATE INDEX IDX_TK_FIELD_ITEM ON TK_VAULT_FIELD(ITEM_ID);
CREATE INDEX IDX_TK_ATT_BIZ ON TK_ATTACHMENT(BIZ_TYPE, BIZ_ID);
CREATE INDEX IDX_TK_ARTICLE_OWNER ON TK_ARTICLE(OWNER, STATUS);
CREATE INDEX IDX_TK_TODO_OWNER ON TK_TODO(OWNER, DONE);
CREATE INDEX IDX_TK_TODO_REMIND ON TK_TODO(REMIND_TIME);

-- 公开互动：聊天室房间、聊天室消息、留言板、文章评论
CREATE TABLE TK_CHAT_ROOM (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
    SORT_ORDER  NUMBER(6) DEFAULT 0 NOT NULL,
    CREATED_BY  VARCHAR2(50),
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE TK_CHAT_MESSAGE (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ROOM_ID     NUMBER NOT NULL REFERENCES TK_CHAT_ROOM(ID) ON DELETE CASCADE,
    AUTHOR_TYPE VARCHAR2(10) NOT NULL,
    AUTHOR_NAME VARCHAR2(50) NOT NULL,
    USERNAME    VARCHAR2(50),
    CONTENT     CLOB NOT NULL,
    STATUS      VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
    SOURCE_HASH VARCHAR2(64),
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_AT TIMESTAMP,
    REVIEWED_BY VARCHAR2(50)
);

CREATE TABLE TK_GUESTBOOK_ENTRY (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    AUTHOR_TYPE VARCHAR2(10) NOT NULL,
    AUTHOR_NAME VARCHAR2(50) NOT NULL,
    USERNAME    VARCHAR2(50),
    CONTENT     CLOB NOT NULL,
    STATUS      VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
    SOURCE_HASH VARCHAR2(64),
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_AT TIMESTAMP,
    REVIEWED_BY VARCHAR2(50)
);

CREATE TABLE TK_ARTICLE_COMMENT (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ARTICLE_ID  NUMBER NOT NULL REFERENCES TK_ARTICLE(ID) ON DELETE CASCADE,
    AUTHOR_TYPE VARCHAR2(10) NOT NULL,
    AUTHOR_NAME VARCHAR2(50) NOT NULL,
    USERNAME    VARCHAR2(50),
    CONTENT     CLOB NOT NULL,
    STATUS      VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
    SOURCE_HASH VARCHAR2(64),
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_AT TIMESTAMP,
    REVIEWED_BY VARCHAR2(50)
);

CREATE INDEX IDX_TK_CHAT_MSG_ROOM ON TK_CHAT_MESSAGE(ROOM_ID, STATUS, CREATED_AT);
CREATE INDEX IDX_TK_GUESTBOOK_STATUS ON TK_GUESTBOOK_ENTRY(STATUS, CREATED_AT);
CREATE INDEX IDX_TK_ART_COMMENT ON TK_ARTICLE_COMMENT(ARTICLE_ID, STATUS, CREATED_AT);

