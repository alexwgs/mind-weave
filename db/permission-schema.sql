-- ============================================================
-- 精细权限模型（SLR_ 前缀，与工具库 TK_ 隔离）
-- 执行方式：java -cp <ojdbc.jar> InitSchema.java db/permission-schema.sql
-- 权限种子数据由后端 DataInitializer 自动写入（幂等）
-- ============================================================

CREATE TABLE SLR_PERMISSION (
    CODE   VARCHAR2(50) PRIMARY KEY,
    NAME   VARCHAR2(100) NOT NULL,
    PGROUP VARCHAR2(50)
);

CREATE TABLE SLR_ROLE_PERMISSION (
    ROLE      VARCHAR2(20) NOT NULL,
    PERM_CODE VARCHAR2(50) NOT NULL,
    PRIMARY KEY (ROLE, PERM_CODE)
);

CREATE TABLE SLR_USER_PERMISSION (
    ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID   NUMBER NOT NULL REFERENCES SLR_APP_USER(ID) ON DELETE CASCADE,
    PERM_CODE VARCHAR2(50) NOT NULL,
    PERM_TYPE VARCHAR2(10) DEFAULT 'ALLOW'   -- ALLOW / DENY
);

-- 用户表增加数据访问范围：ALL=全部 / GRADES=仅指定级别 / NONE=无
ALTER TABLE SLR_APP_USER ADD (DATA_SCOPE VARCHAR2(10) DEFAULT 'ALL');
ALTER TABLE SLR_APP_USER ADD (SCOPE_GRADES VARCHAR2(500));

CREATE INDEX IDX_TK_USER_PERM ON SLR_USER_PERMISSION(USER_ID);
